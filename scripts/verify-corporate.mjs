import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
const read = (path) => readFileSync(path, "utf8");
const page = read("src/app/page.tsx");
const products = read("src/data/corporate-products.ts");
const layout = read("src/app/layout.tsx");
const css = ["globals.css", "corporate-sections.css", "corporate-responsive.css"].map(name => read(`src/app/${name}`)).join("\n");
const analytics = read("src/components/analytics/product-intent-analytics.tsx");
const mobile = read("src/components/corporate/mobile-navigation.tsx");
const moments = read("src/components/corporate/product-moment-v2.tsx");
const site = read("src/data/site.ts");

// Guard public truth and meaningful contracts, not incidental marketing wording.
assert.match(page, /Tu próximo<br\s*\/>paso,/);
assert.equal((page.match(/<h1\b/g) || []).length, 1);
assert.equal((page.match(/<section\b/g) || []).length, 5);
for (const id of ["contenido", "productos", "criterio", "en-desarrollo", "como-funciona"]) {
  assert.ok(page.includes(`id="${id}"`), `Missing destination ${id}`);
}
assert.match(page, /Saltar al contenido/);
const [available, planned] = products.split("export const upcomingInitiatives");
assert.ok(planned, "Development initiatives have a separate representation");
for (const url of ["https://www.voltastore.app", "https://volta-booking.vercel.app", "https://www.voltaportfolio.app"]) assert.ok(available.includes(url));
assert.equal((available.match(/href: "/g) || []).length, 3);
assert.match(available, /status: "En evolución"/);
for (const name of ["VOLTA Shield", "VOLTA Bridge", "VOLTA Automate"]) assert.ok(planned.includes(name));
assert.doesNotMatch(planned, /href:|Disponible|Próximamente/);
assert.match(planned, /En exploración/);
assert.match(page, /todavía no están abiertas al público general/);
assert.match(moments, /Vista ilustrativa/);
assert.match(moments, /aria-hidden="true"/);
assert.doesNotMatch(moments, /<button|<input|<a\s/);
assert.match(layout, /Instrument_Sans/);
assert.match(layout, /metadataBase: new URL\(siteUrl\)/);
assert.match(layout, /<ProductIntentAnalytics \/>/);
assert.match(layout, /<Analytics \/>/);
assert.match(site, /VOLTA \| Tu próximo paso, online\./);
assert.match(site, /https:\/\/volta-landing-delta\.vercel\.app/);
assert.doesNotMatch(site, /process\.env\.VERCEL_URL/);
for (const role of ["--volta-canvas:", "--action-foreground:", "--focus-ring:", "prefers-reduced-motion: reduce", "forced-colors: active"]) assert.ok(css.includes(role));
assert.match(css, /#00e878/i);
assert.match(mobile, /aria-expanded=\{open\}/);
assert.match(mobile, /aria-controls="mobile-menu"/);
assert.match(mobile, /Escape/);
assert.match(analytics, /track\("Product selected"/);
assert.match(analytics, /corporateProducts/);
assert.match(analytics, /anchor\.dataset\.productPlacement/);
for (const path of ["src/app/robots.ts", "src/app/sitemap.ts", "src/app/opengraph-image.tsx"]) assert.ok(existsSync(path));
const manifest = JSON.parse(read("public/site.webmanifest"));
assert.equal(manifest.name, "VOLTA");
assert.equal(manifest.start_url, "/");
for (const path of ["src/app/volta-flow.css", "src/components/corporate/hero-switchboard.tsx", "src/components/corporate/volta-flow.tsx", "src/data/landing-content.ts"]) assert.ok(!existsSync(path), `Retired presentation revived: ${path}`);
console.log("VOLTA Corporate: portfolio truth, navigation, visual, metadata and analytics contracts passed.");
