/** Public truth and asset contracts. No marketing-copy snapshot assertions. */
import assert from "node:assert/strict";
import { existsSync, readFileSync, statSync } from "node:fs";
import sharp from "sharp";
const read = path => readFileSync(path, "utf8");
const page = read("src/app/page.tsx");
const data = read("src/data/corporate-products.ts");
const layout = read("src/app/layout.tsx");
const globals = read("src/app/globals.css");
const css = globals + read("src/app/home.module.css");
const site = read("src/data/site.ts");
const analytics = read("src/components/analytics/product-intent-analytics.tsx");
const nav = read("src/components/corporate/mobile-navigation.tsx");
const provenance = JSON.parse(read("public/showcase/provenance.json"));
const keys = ["store", "booking", "portfolio"];
assert.equal((page.match(/<h1\b/g) || []).length, 1);
assert.equal((page.match(/<section\b/g) || []).length, 5, "Five distinct chapters, no stock gallery or redundant process section");
for (const id of ["contenido", "productos", "criterio", "en-desarrollo", "shield", "bridge", "automate", "como-funciona"]) assert.ok(page.includes(`id="${id}"`), id);
assert.match(page, /Saltar al contenido/);
assert.match(page, /upcomingInitiatives/);
assert.match(page, /corporateProducts\.map/);
assert.match(page, /next\/image/);
assert.match(page, /<picture>/);
assert.match(page, /srcSet=/);
assert.match(page, /sizes=/);
assert.match(page, /media\.alt/);
assert.match(page, /media\.caption/);
assert.match(page, /<figcaption>/);
assert.match(page, /loading=/);
assert.match(page, /unoptimized/);
assert.doesNotMatch(page, /https:\/\/(?:images\.pexels\.com|images\.unsplash\.com)|backgroundImage|ProductMoment|heroNode/);
const [available, planned] = data.split("export const upcomingInitiatives");
assert.ok(planned);
for (const url of ["https://www.voltastore.app", "https://volta-booking.vercel.app", "https://www.voltaportfolio.app"]) assert.ok(available.includes(url));
assert.equal((available.match(/href:/g) || []).length, 4);
assert.match(available, /status: "En evolución"/);
for (const name of ["VOLTA Shield", "VOLTA Bridge", "VOLTA Automate"]) assert.ok(planned.includes(name));
for (const status of ["En validación", "En desarrollo", "En exploración"]) assert.ok(planned.includes(status));
assert.doesNotMatch(planned, /href:|status: "Disponible"|Próximamente|100%|certificad/);
assert.match(planned, /Aún no disponible de forma general/);
assert.match(planned, /condiciones justas/);
assert.match(planned, /sin fecha de lanzamiento/);
assert.match(layout, /Instrument_Sans/);
assert.match(layout, /metadataBase: new URL\(siteUrl\)/);
assert.match(layout, /<ProductIntentAnalytics \/>/);
assert.match(layout, /<Analytics \/>/);
assert.match(site, /https:\/\/volta-landing-delta\.vercel\.app/);
assert.doesNotMatch(site, /process\.env\.VERCEL_URL/);
for (const token of ["--volta-canvas:", "--action-foreground:", "--focus-ring:", "prefers-reduced-motion: reduce", "forced-colors: active"]) assert.ok(css.includes(token));
assert.match(globals, /#00e878/i);
assert.match(nav, /aria-expanded=\{open\}/);
assert.match(nav, /aria-controls="mobile-menu"/);
assert.match(nav, /Escape/);
assert.match(analytics, /track\("Product selected"/);
assert.match(analytics, /corporateProducts/);
assert.match(analytics, /anchor\.dataset\.productPlacement/);
assert.equal(provenance.length, 3);
let totalBytes = 0;
for (const key of keys) {
  const source = provenance.find(p => p.key === key);
  assert.ok(source?.url?.startsWith("https://"), `Source ${key}`);
  assert.ok(source.capturedAt && source.kind && source.width && source.height);
  assert.ok(available.includes(`width: ${source.width}, height: ${source.height}`), `Source dimensions match presentation: ${key}`);
  for (const width of [640, 960, 1600]) {
    const path = `public/showcase/${key}-${width}.webp`;
    const bytes = statSync(path).size;
    totalBytes += bytes;
    const image = await sharp(path).metadata();
    assert.equal(image.format, "webp");
    assert.equal(image.width, Math.min(width, source.width), `${path} truthful srcset width`);
    assert.ok(Math.abs(image.height - image.width * source.height / source.width) <= 1, `Aspect ratio ${path}`);
    assert.ok(bytes < 200_000, `Per-asset budget: ${path}`);
  }
}
assert.ok(totalBytes < 800_000, `Total responsive image variants: ${totalBytes}`);
for (const path of ["src/app/robots.ts", "src/app/sitemap.ts", "src/app/opengraph-image.tsx"]) assert.ok(existsSync(path));
const manifest = JSON.parse(read("public/site.webmanifest"));
assert.equal(manifest.name, "VOLTA");
assert.equal(manifest.start_url, "/");
for (const path of ["src/app/volta-flow.css", "src/components/corporate/hero-switchboard.tsx", "src/components/corporate/volta-flow.tsx", "src/components/corporate/product-moment-v2.tsx", "src/app/corporate-sections.css", "src/app/corporate-responsive.css"]) assert.ok(!existsSync(path), `Retired presentation: ${path}`);
const deployment = JSON.parse(read("vercel.json"));
assert.equal(deployment.git.deploymentEnabled["feat/corporate-v1-final"], false);
assert.notEqual(deployment.git.deploymentEnabled.main, false);
console.log(`VOLTA Corporate v1: portfolio truth, 5 chapters, local media/provenance (${totalBytes} bytes), semantics, tokens, metadata and deployment contracts passed.`);
